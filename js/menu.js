// pre-match variant pick for the local slot, full heal like setClass since
// nothing has been risked yet. The pick plays on the preview body: gearFxT
// runs the white flash and the sparkles, gearFxSlot lights the piece's band.
function pickGear(i, v) {
  if (player.gear[i] === v) return;
  player.gear[i] = v;
  refreshKit(player);
  player.hp = player.maxHp;
  state.menu.gearFxT = 0.45;
  state.menu.gearFxSlot = i;
  SFX.pickup();
}

function gearKey(k) {
  const m = state.menu;
  if (m.lockT > 0) return;
  if (k === 'escape' || k === 'backspace' || k === 'enter' || k === ' ') leaveGear();
  else if (k === 'arrowup' || k === 'w') { m.grow = (m.grow + 3) % 4; SFX.pickup(); }
  else if (k === 'arrowdown' || k === 's') { m.grow = (m.grow + 1) % 4; SFX.pickup(); }
  else if (k === 'arrowleft' || k === 'a') pickGear(m.grow, (player.gear[m.grow] + 2) % 3);
  else if (k === 'arrowright' || k === 'd') pickGear(m.grow, (player.gear[m.grow] + 1) % 3);
}

function gearClick() {
  const m = state.menu;
  if (m.lockT > 0 || m.gearT < 1) return;
  const h = gearScreenHit();
  if (!h || h === 'x') { leaveGear(); return; } // the X, or anywhere off the panel
  if (h === 'panel') return;                    // the slab swallows it
  m.grow = h.row;
  pickGear(h.row, h.v);
}

// what the pointer is over: portrait index, CLASSES.length for PLAY,
// CLASSES.length + 1 for the collapsed gear widget, CLASSES.length + 2 + k
// for difficulty notch k, -1 for nothing
function selectHit() {
  const { ports, play, loadout, diff } = selectLayout();
  const over = (r, px, py) => mouse.x >= r.x - px && mouse.x < r.x + r.w + px && mouse.y >= r.y - py && mouse.y < r.y + r.h + py;
  for (let i = 0; i < ports.length; i++) if (over(ports[i], 2, 2)) return i;
  if (over(play, 2, 3)) return ports.length;
  if (over(loadout, 3, 2)) return ports.length + 1;
  for (let k = 0; k < diff.length; k++) if (over(diff[k], 2, 3)) return ports.length + 2 + k;
  return -1;
}

